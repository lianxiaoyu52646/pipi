from playwright.sync_api import sync_playwright
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage','--disable-web-security','--allow-file-access-from-files'])
 page=browser.new_page(viewport={'width':390,'height':844}, device_scale_factor=1, is_mobile=True, has_touch=True)
 errors=[]
 page.on('pageerror',lambda error: errors.append(str(error)))
 page.goto('file:///mnt/data/pipi_v54/app/src/main/assets/index.html',wait_until='domcontentloaded',timeout=30000)
 page.wait_for_timeout(1500)
 print('home title',page.title(), 'errors',errors[:3]);print('navigation',page.locator('[data-page="train"]').count())
 page.locator('[data-page="train"]').first.click()
 page.wait_for_timeout(400)
 print('book list count',page.locator('[data-book="primary"]').count())
 page.locator('[data-book="primary"]').first.click()
 page.wait_for_timeout(1700)
 print('mode counts',page.locator('[data-action="word-mode-list"]').count(), 'status',page.locator('.pipi-studytop').all_text_contents())
 page.locator('[data-action="word-mode-list"]').click()
 page.wait_for_timeout(600)
 print('list rendered',page.locator('.pipi-list-row').count(), 'count',page.locator('#pipiListRange').inner_text(), 'error', errors[:3])
 page.screenshot(path='/mnt/data/pipi_v54_list.png')
 page.locator('[data-action="list-unknown"]').first.click()
 print('mark',page.locator('[data-action="list-unknown"]').first.inner_text())
 page.locator('[data-action="word-display-both"]').click()
 page.wait_for_timeout(200)
 print('meanings',page.locator('.pipi-list-meaning:not([hidden])').count())
 page.locator('#viewport').evaluate('el=>el.scrollTop=2000')
 page.wait_for_timeout(300)
 print('after scroll',page.locator('#pipiListRange').inner_text(), 'row first',page.locator('.pipi-list-row').first.get_attribute('data-row-index'))
 page.locator('[data-action="word-mode-card"]').click()
 page.wait_for_timeout(200)
 print('card Chinese shown',page.locator('#fastWordAnswer').get_attribute('hidden'))
 page.locator('[data-action="word-display-english"]').click()
 page.wait_for_timeout(200)
 print('card Chinese hidden',page.locator('#fastWordAnswer').get_attribute('hidden'))
 page.locator('[data-action="flip-word"]').click()
 print('after eye',page.locator('#fastWordAnswer').get_attribute('hidden'))
 page.locator('[data-grade="known"]').first.click()
 page.wait_for_timeout(300)
 print('after next',page.locator('#fastWordAnswer').get_attribute('hidden'))
 print('errors final',errors)
 # reader
 rp=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1,is_mobile=True,has_touch=True)
 err2=[]
 rp.on('pageerror',lambda error:err2.append(str(error)))
 rp.goto('file:///mnt/data/pipi_v54/app/src/main/assets/originals-reader.html',wait_until='domcontentloaded',timeout=30000)
 rp.wait_for_timeout(1200)
 print('reader books',rp.locator('[data-book]').count())
 rp.locator('[data-book="alice"]').first.click() if rp.locator('[data-book="alice"]').count() else rp.locator('[data-book]').first.click()
 rp.wait_for_timeout(2800)
 print('reader text length',len(rp.locator('#readingText').inner_text()),'reader pages',rp.locator('.reader-stream-chunk').count(),'errors',err2[:5])
 print('reader scroll height',rp.locator('#readingText').evaluate('e=>[e.scrollHeight,e.clientHeight]'))
 rp.screenshot(path='/mnt/data/pipi_v54_reader.png')
 for i in range(12):
  rp.locator('#readingText').evaluate('e=>e.scrollTop+=480')
  rp.wait_for_timeout(100)
 print('after scroll',rp.locator('.reader-stream-chunk').count(), 'metric',rp.locator('#readingPercent').inner_text(),'error',err2[:6])
 print('last chapter',rp.locator('.reader-stream-chunk').last.get_attribute('data-chapter'))
 browser.close()
