vm.runInContext(script.slice(i,j),ctx);
assert.equal(vm.runInContext('JSON.stringify(nextRef({chapter:0,page:1}))',ctx),'{"chapter":1,"page":0}','next scroll moves chapter');
assert.equal(vm.runInContext('JSON.stringify(prevRef({chapter:1,page:0}))',ctx),'{"chapter":0,"page":1}','scroll up previous chapter');
assert.equal(vm.runInContext('nextRef({chapter:2,page:1})',ctx),null,'end of novel is bounded');
assert.equal(vm.runInContext('prevRef({chapter:0,page:0})',ctx),null,'start of novel is bounded');
console.log('PASS: vertical continuous reader, no horizontal pagination, bounded DOM, bidirectional chapter references');
