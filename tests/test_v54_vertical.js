'use strict';
const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('node:assert/strict');
const root=path.join(__dirname,'../app/src/main/assets');
const html=fs.readFileSync(path.join(root,'originals-reader.html'),'utf8');
const script=fs.readFileSync(path.join(root,'originals-reader.js'),'utf8');
assert(!html.includes('id="prevPage"')&&!html.includes('id="nextPage"'),'no page buttons');
assert(html.includes('上下滑动连续阅读'),'reader invites vertical scrolling');
assert(!script.includes("addEventListener('touchend'"),'horizontal swipe removed');
assert(script.includes('STREAM_MAX=14'),'reader DOM bounded');
const css=fs.readFileSync(path.join(root,'originals-reader.css'),'utf8');
assert(css.includes('overflow-y:auto')&&css.includes('-webkit-overflow-scrolling:touch'));
const i=script.indexOf('const STREAM_MAX=14'),j=script.indexOf('function speak(text){',i);
assert(i>=0&&j>i);
const el={addEventListener(){}};
const ctx={console,ctx:{book:{id:'alice'},work:{sections:[{}, {}, {}]}},paginateChapter:()=>[{start:0,parts:[]},{start:999,parts:[]}],$:()=>el,requestAnimationFrame:()=>{},markedSet:()=>new Set(),richParagraph:()=>'',esc:x=>x,document:{},setProgress:()=>{}};
