'use strict';
const fs = require('fs'); const assert=require('node:assert/strict'); const path=require('path');
const a=path.resolve(__dirname,'../app/src/main/assets');
const html=fs.readFileSync(path.join(a,'originals-reader.html'),'utf8');
const js=fs.readFileSync(path.join(a,'originals-reader.js'),'utf8');
const css=fs.readFileSync(path.join(a,'reader-modern.css'),'utf8');
const pos=id=>html.indexOf('id="'+id+'"');
for(const id of ['readerSettingsButton','focusReading','playPart','stopArticle','focusPlay','focusExit','articleVoiceStatus']) assert(pos(id)>=0,id);
assert(pos('readerSettingsButton')<pos('focusReading')&&pos('focusReading')<pos('playPart'),'read tools button ordering');
assert(pos('stopArticle')>pos('playPart'),'stop next to play, only shown during speech');
assert(!html.includes('class="article-player-bar"'),'bottom bar removed');
assert(!html.includes('id="playerPercent"'),'redundant progress hidden');
assert(!html.includes('离线女声 · 点击开始朗读'),'redundant hint removed');
assert(pos('articleVoiceStatus')>pos('readingText'),'screen reader updates preserved');
assert(css.includes('body.reading-active .reading-progress-track{display:none!important;}'),'no progress bar crowding reader');
assert(css.includes('.screen-reader-only')&&css.includes('.focus-play'),'accessible status and fullscreen action');
assert(js.includes("$('focusPlay').addEventListener('click',()=>$('playPart').click());"),'fullscreen button shares handler');
assert(js.includes("end.hidden=!narrator.active"),'stop button toggle preserved');
assert(js.includes("btn.setAttribute('aria-pressed',String(narrator.active&&!narrator.paused))"),'speech aria reflects state');
assert(!css.includes('body.reading-active .article-player-bar'),'no wasted footer height');
console.log('PASS: top speech placement, removal of redundant bottom UI, preserved stop/focus/screenreader behavior');
