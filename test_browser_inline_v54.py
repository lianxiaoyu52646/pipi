from pathlib import Path
from playwright.sync_api import sync_playwright
import re
root=Path('/mnt/data/pipi_v54/app/src/main/assets')
def create_page(browser,name):
 p=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1, is_mobile=True, has_touch=True)
 errors=[];p.on('pageerror',lambda e:errors.append(str(e)))
 html=(root/name).read_text()
 scripts=re.findall(r'<script[^>]*\bsrc="([^"]+)"[^>]*></script>',html)
 html=re.sub(r'<script[^>]*\bsrc="[^"]+"[^>]*></script>','',html)
 html=re.sub(r'<link[^>]*\brel="stylesheet"[^>]*>','',html)
 p.set_content(html,wait_until='domcontentloaded')
 for file in scripts:
  print('load',file,flush=True)
  p.add_script_tag(content=(root/file.removeprefix('./')).read_text())
 if name=='index.html':
  for st in ['styles.css','v5-styles.css']: p.add_style_tag(content=(root/st).read_text())
 else: p.add_style_tag(content=(root/'originals-reader.css').read_text())
 return p,errors
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
 page,errors=create_page(browser,'index.html')
 page.wait_for_timeout(700)
 print('errors home',errors[:3])
 page.locator('[data-page="train"]').first.click()
 page.locator('[data-book="primary"]').first.click()
 page.wait_for_timeout(600)
 print('mode buttons',page.locator('[data-action="word-mode-list"]').count())
 page.locator('[data-action="word-mode-list"]').click()
 page.wait_for_timeout(250)
 print('rows',page.locator('.pipi-list-row').count(), 'range',page.locator('#pipiListRange').inner_text())
 page.screenshot(path='/mnt/data/pipi_v54_list.png')
 page.locator('[data-action="list-unknown"]').first.click()
 print('mark',page.locator('[data-action="list-unknown"]').first.inner_text())
 page.locator('[data-action="word-display-both"]').click()
 page.wait_for_timeout(150)
 print('visible meanings',page.locator('.pipi-list-meaning:not([hidden])').count())
 page.locator('#viewport').evaluate('(el)=>el.scrollTop=2500')
 page.wait_for_timeout(250)
 print('scroll',page.locator('#pipiListRange').inner_text(),'first',page.locator('.pipi-list-row').first.get_attribute('data-row-index'))
 page.locator('[data-action="word-mode-card"]').click()
 page.wait_for_timeout(150)
 print('card translation visible?',page.locator('#fastWordAnswer').get_attribute('hidden'))
 page.locator('[data-action="word-display-english"]').click()
 page.wait_for_timeout(100)
 print('card translation hidden?',page.locator('#fastWordAnswer').get_attribute('hidden'))
 page.locator('[data-action="flip-word"]').click()
 print('temporary eye',page.locator('#fastWordAnswer').get_attribute('hidden'))
 page.locator('[data-grade="known"]').click()
 page.wait_for_timeout(150)
 print('next word hidden',page.locator('#fastWordAnswer').get_attribute('hidden'))
 print('errors app',errors[:5])
 reader,err2=create_page(browser,'originals-reader.html')
 reader.wait_for_timeout(400)
 print('books',reader.locator('[data-book]').count())
 reader.locator('[data-book]').first.click()
 reader.wait_for_timeout(650)
 print('stream rows',reader.locator('.reader-stream-chunk').count(), 'reader errors',err2[:6])
 print('reader scroll',reader.locator('#readingText').evaluate('(el)=>[el.clientHeight,el.scrollHeight]'))
 reader.screenshot(path='/mnt/data/pipi_v54_reader.png')
 for i in range(25):
  reader.locator('#readingText').evaluate('(el)=>el.scrollTop+=400')
  reader.wait_for_timeout(65)
 print('after scroll',reader.locator('.reader-stream-chunk').count(),reader.locator('#readingPercent').inner_text(), 'errors',err2[:6])
 browser.close()
